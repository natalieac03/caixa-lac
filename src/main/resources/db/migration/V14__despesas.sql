CREATE TABLE despesa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data DATE NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    categoria_id BIGINT NOT NULL,
    valor NUMERIC(38,2) NOT NULL,
    evento_id BIGINT,
    observacao VARCHAR(255),
    registrada_em TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_despesa_categoria FOREIGN KEY (categoria_id) REFERENCES categoria_despesa(id),
    CONSTRAINT fk_despesa_evento FOREIGN KEY (evento_id) REFERENCES evento(id),
    CONSTRAINT ck_despesa_valor CHECK (valor > 0)
);
CREATE INDEX ix_despesa_data ON despesa(data);
CREATE INDEX ix_despesa_evento ON despesa(evento_id);
CREATE INDEX ix_despesa_categoria ON despesa(categoria_id);
