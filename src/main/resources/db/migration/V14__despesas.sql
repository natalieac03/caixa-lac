-- Despesas do grupo (material, transporte...). Compras de mercadoria NÃO são
-- despesa: entram pela entrada de estoque (compra_estoque) e viram custo da
-- mercadoria vendida pelo custo do item. Evento é opcional e explícito.

-- Categorias de despesa: tabela própria, editável pela tela.
CREATE TABLE categoria_despesa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(60) NOT NULL,
    nome_normalizado VARCHAR(60) NOT NULL,
    CONSTRAINT uk_categoria_despesa_nome UNIQUE (nome_normalizado)
);
