-- Pagamento dividido: cada venda passa a ter linhas de pagamento (forma + valor).
-- Roda igual no PostgreSQL e no H2 local.

-- Para a migração, com mensagem clara, se houver venda sem valor ou com valor
-- negativo: a conversão do texto para número falha e a mensagem aparece no erro.
-- Não se inventa valor: corrija a venda com dados confirmados pela LAC e rode de novo.
SELECT CAST('V6 parada: a venda ' || CAST(id AS VARCHAR(20))
            || ' não tem valor_cobrado nem valor_total. Informe o valor e rode de novo.' AS INTEGER)
FROM venda WHERE valor_cobrado IS NULL AND valor_total IS NULL;
SELECT CAST('V6 parada: a venda ' || CAST(id AS VARCHAR(20))
            || ' tem valor negativo. Corrija o valor e rode de novo.' AS INTEGER)
FROM venda WHERE COALESCE(valor_cobrado, valor_total) < 0;

CREATE TABLE pagamento_venda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venda_id BIGINT NOT NULL,
    forma VARCHAR(255) NOT NULL,
    valor NUMERIC(38,2) NOT NULL,
    descricao VARCHAR(255),
    valor_recebido NUMERIC(38,2),
    CONSTRAINT fk_pagamento_venda_venda FOREIGN KEY (venda_id) REFERENCES venda(id),
    CONSTRAINT ck_pagamento_venda_forma CHECK (forma IN ('CREDITO','DEBITO','DINHEIRO','OUTRO','PIX')),
    CONSTRAINT ck_pagamento_venda_valor CHECK (valor > 0),
    -- Recebido só em dinheiro e nunca menor que a parte (troco >= 0).
    CONSTRAINT ck_pagamento_venda_recebido CHECK (
        valor_recebido IS NULL OR (forma = 'DINHEIRO' AND valor_recebido >= valor))
);
CREATE INDEX idx_pagamento_venda_forma ON pagamento_venda(forma);
CREATE INDEX idx_pagamento_venda_venda ON pagamento_venda(venda_id);

-- Cada venda existente vira UMA linha com a forma e o valor que já tinha,
-- canceladas inclusive (continuam fora dos totais pela venda). Valor zero
-- (cortesia) não ganha linha.
INSERT INTO pagamento_venda (venda_id, forma, valor, descricao)
SELECT id, forma_pagamento, COALESCE(valor_cobrado, valor_total), forma_pagamento_outro
FROM venda
WHERE COALESCE(valor_cobrado, valor_total) > 0
ORDER BY id;

-- A coluna antiga fica sem uso (remover numa versão futura); vendas novas não a preenchem.
ALTER TABLE venda ALTER COLUMN forma_pagamento DROP NOT NULL;
