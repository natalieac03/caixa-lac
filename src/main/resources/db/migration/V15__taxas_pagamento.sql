-- Taxas por forma de pagamento (maquininha, Pix...): percentual + valor fixo por
-- transação, com data de vigência. Vale para a venda a taxa da forma com a maior
-- vigência que não seja depois do dia da venda. A venda grava a taxa estimada
-- em cada parte do pagamento: mudar a taxa depois não altera vendas passadas.
CREATE TABLE taxa_pagamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forma VARCHAR(20) NOT NULL,
    percentual NUMERIC(7,4) NOT NULL,
    valor_fixo NUMERIC(38,2) NOT NULL,
    vigente_desde DATE NOT NULL,
    registrada_em TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_taxa_pagamento_forma CHECK (forma IN ('CREDITO','DEBITO','DINHEIRO','OUTRO','PIX')),
    CONSTRAINT ck_taxa_pagamento_percentual CHECK (percentual >= 0 AND percentual <= 100),
    CONSTRAINT ck_taxa_pagamento_fixo CHECK (valor_fixo >= 0),
    CONSTRAINT uk_taxa_pagamento_vigencia UNIQUE (forma, vigente_desde)
);

