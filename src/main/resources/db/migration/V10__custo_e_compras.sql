-- Custo dos produtos para as finanças. Nada muda no que o cliente paga.
-- Custos com 4 casas: o custo médio ponderado é uma divisão e perderia centavos
-- a cada compra se fosse arredondado para 2.

-- Custo unitário atual do produto (opcional; sem custo = ainda não informado).
ALTER TABLE produto ADD COLUMN custo_unitario NUMERIC(38,4);
ALTER TABLE produto ADD CONSTRAINT ck_produto_custo CHECK (custo_unitario IS NULL OR custo_unitario >= 0);

-- Custo congelado no item da venda, como o preço unitário. Vendas antigas ficam
-- com NULL: não se inventa custo.
ALTER TABLE item_venda ADD COLUMN custo_unitario NUMERIC(38,4);
ALTER TABLE item_venda ADD CONSTRAINT ck_item_venda_custo CHECK (custo_unitario IS NULL OR custo_unitario >= 0);

-- Entrada de estoque por compra: o documento da compra e o cálculo do custo médio
-- (antes e depois), para conferência.
CREATE TABLE compra_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    custo_total NUMERIC(38,2) NOT NULL,
    data_compra DATE NOT NULL,
    observacao VARCHAR(255),
    estoque_anterior INTEGER NOT NULL,
    custo_anterior NUMERIC(38,4),
    custo_novo NUMERIC(38,4) NOT NULL,
    registrada_em TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_compra_estoque_produto FOREIGN KEY (produto_id) REFERENCES produto(id),
    CONSTRAINT ck_compra_estoque_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_compra_estoque_custo CHECK (custo_total >= 0 AND custo_novo >= 0),
    CONSTRAINT ck_compra_estoque_estoque CHECK (estoque_anterior >= 0)
);
CREATE INDEX idx_compra_estoque_produto ON compra_estoque(produto_id);
