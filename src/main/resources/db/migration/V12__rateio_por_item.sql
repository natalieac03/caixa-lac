-- Desconto da venda rateado por item: valor bruto (preço normal x quantidade),
-- parte do desconto (promoções + ajuste manual, com sinal) e valor líquido.
-- A soma dos líquidos de uma venda é exatamente o valor cobrado.
-- Roda igual no PostgreSQL e no H2 (só inteiros nas contas de centavos).

ALTER TABLE item_venda ADD COLUMN valor_bruto NUMERIC(38,2);
ALTER TABLE item_venda ADD COLUMN desconto_rateado NUMERIC(38,2);
ALTER TABLE item_venda ADD COLUMN valor_liquido NUMERIC(38,2);

-- true = rateio reconstruído aqui a partir dos totais, não na hora da venda.
ALTER TABLE venda ADD COLUMN rateio_retroativo BOOLEAN DEFAULT FALSE NOT NULL;

-- Descontos promocionais de cada venda, com a descrição congelada.
CREATE TABLE venda_desconto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venda_id BIGINT NOT NULL,
    promocao_id BIGINT,
    descricao VARCHAR(255) NOT NULL,
    valor NUMERIC(38,2) NOT NULL,
    CONSTRAINT fk_venda_desconto_venda FOREIGN KEY (venda_id) REFERENCES venda(id),
    -- Apagar a promoção não apaga o histórico: só perde o vínculo.
    CONSTRAINT fk_venda_desconto_promocao FOREIGN KEY (promocao_id) REFERENCES promocao(id) ON DELETE SET NULL,
    CONSTRAINT ck_venda_desconto_valor CHECK (valor >= 0)
);
CREATE INDEX ix_venda_desconto_venda ON venda_desconto(venda_id);
CREATE INDEX ix_venda_desconto_promocao ON venda_desconto(promocao_id);

-- Vendas antigas ---------------------------------------------------------------
-- Não se inventa preço: item antigo sem preco_unitario para a migração com a
-- mensagem no erro (o CAST do texto para número falha). Corrija e rode de novo.
SELECT CAST('V12 parada: o item ' || CAST(id AS VARCHAR(20)) || ' da venda ' || CAST(venda_id AS VARCHAR(20))
            || ' não tem preco_unitario. Informe o preço confirmado pela LAC e rode de novo.' AS INTEGER)
FROM item_venda WHERE preco_unitario IS NULL;

-- 1. Bruto das vendas antigas: o preço unitário gravado (já com A_PARTIR_DE, se houve).
UPDATE item_venda SET valor_bruto = preco_unitario * quantidade;

-- 2. Por venda: desconto a ratear (soma dos brutos - cobrado, em centavos, com sinal).
--    Sem os valores calculados da época, rateia-se a diferença para o cobrado.
--    Peso = bruto; se todos os brutos forem zero, a quantidade (como Rateio.java).
CREATE TABLE v12_venda AS
SELECT i.venda_id,
       CAST(ROUND(SUM(i.valor_bruto) * 100, 0) AS BIGINT) - CAST(ROUND(v.valor_cobrado * 100, 0) AS BIGINT) AS desconto,
       CAST(ROUND(SUM(i.valor_bruto) * 100, 0) AS BIGINT) AS soma_bruto,
       CAST(SUM(i.quantidade) AS BIGINT) AS soma_qtd
FROM item_venda i JOIN venda v ON v.id = i.venda_id
GROUP BY i.venda_id, v.valor_cobrado;

CREATE TABLE v12_item AS
SELECT i.id AS item_id,
       i.venda_id,
       ABS(r.desconto) AS modulo,
       SIGN(r.desconto) AS sinal,
       CASE WHEN r.soma_bruto > 0 THEN CAST(ROUND(i.valor_bruto * 100, 0) AS BIGINT)
            ELSE CAST(i.quantidade AS BIGINT) END AS peso,
       CASE WHEN r.soma_bruto > 0 THEN r.soma_bruto ELSE r.soma_qtd END AS soma_peso
FROM item_venda i JOIN v12_venda r ON r.venda_id = i.venda_id;

-- 3. Maior resto: piso de modulo x peso / soma_peso (divisão inteira) e os centavos
--    que sobram, um a um, para os maiores restos (empate: menor id do item).
CREATE TABLE v12_piso AS
SELECT item_id,
       venda_id,
       modulo,
       sinal,
       CASE WHEN soma_peso = 0 THEN 0 ELSE (modulo * peso) / soma_peso END AS piso,
       CASE WHEN soma_peso = 0 THEN 0 ELSE MOD(modulo * peso, soma_peso) END AS resto
FROM v12_item;

CREATE TABLE v12_parte AS
SELECT o.item_id,
       o.sinal * (o.piso + CASE WHEN o.ordem <= o.modulo - o.soma_piso THEN 1 ELSE 0 END) AS parte
FROM (SELECT p.item_id,
             p.modulo,
             p.sinal,
             p.piso,
             ROW_NUMBER() OVER (PARTITION BY p.venda_id ORDER BY p.resto DESC, p.item_id) AS ordem,
             SUM(p.piso) OVER (PARTITION BY p.venda_id) AS soma_piso
      FROM v12_piso p) o;

UPDATE item_venda SET desconto_rateado =
    (SELECT CAST(r.parte AS NUMERIC(38,2)) * 0.01 FROM v12_parte r WHERE r.item_id = item_venda.id);
UPDATE item_venda SET valor_liquido = valor_bruto - desconto_rateado;

-- 4. Marca as vendas antigas que ganharam rateio (as sem itens não têm o que ratear).
UPDATE venda SET rateio_retroativo = TRUE WHERE id IN (SELECT venda_id FROM v12_venda);

-- Conferência: em toda venda rateada, soma dos líquidos = cobrado.
SELECT CAST('V12 parada: o rateio da venda ' || CAST(v.id AS VARCHAR(20)) || ' não fecha com o valor cobrado.' AS INTEGER)
FROM venda v
WHERE v.rateio_retroativo
  AND v.valor_cobrado <> (SELECT SUM(i.valor_liquido) FROM item_venda i WHERE i.venda_id = v.id);

DROP TABLE v12_parte;
DROP TABLE v12_piso;
DROP TABLE v12_item;
DROP TABLE v12_venda;
