-- Equivalente ao modelo Hibernate antes da troca das tabelas de junção.
-- IDs e valores monetários preservam os tipos e a precisão atuais.
-- VARCHAR + CHECK substitui o ENUM nativo do H2 para portabilidade com Postgres.
CREATE TABLE categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    nome_normalizado VARCHAR(255),
    CONSTRAINT uk_categoria_nome_normalizado UNIQUE (nome_normalizado)
);
CREATE TABLE produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo BOOLEAN NOT NULL,
    nome VARCHAR(255),
    preco NUMERIC(38,2),
    quantidade INTEGER NOT NULL,
    versao BIGINT DEFAULT 0 NOT NULL,
    categoria_id BIGINT REFERENCES categoria(id)
);
CREATE TABLE venda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora TIMESTAMP(6),
    forma_pagamento VARCHAR(255) CHECK (forma_pagamento IN ('CREDITO','DEBITO','DINHEIRO','OUTRO','PIX')),
    forma_pagamento_outro VARCHAR(255),
    valor_total NUMERIC(38,2),
    valor_calculado NUMERIC(38,2),
    desconto NUMERIC(38,2),
    valor_cobrado NUMERIC(38,2),
    motivo_ajuste VARCHAR(255),
    token VARCHAR(255)
);
CREATE UNIQUE INDEX uk_venda_token ON venda(token);
CREATE TABLE item_venda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    preco_unitario NUMERIC(38,2),
    quantidade INTEGER NOT NULL,
    produto_id BIGINT REFERENCES produto(id)
);
CREATE TABLE venda_itens (
    venda_id BIGINT NOT NULL REFERENCES venda(id),
    itens_id BIGINT NOT NULL UNIQUE REFERENCES item_venda(id)
);
CREATE TABLE promocao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo BOOLEAN NOT NULL,
    preco NUMERIC(38,2),
    tipo VARCHAR(255) CHECK (tipo IN ('A_PARTIR_DE','PACOTE'))
);
CREATE TABLE promocao_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantidade INTEGER NOT NULL,
    categoria_id BIGINT REFERENCES categoria(id)
);
CREATE TABLE promocao_itens (
    promocao_id BIGINT NOT NULL REFERENCES promocao(id),
    itens_id BIGINT NOT NULL UNIQUE REFERENCES promocao_item(id)
);
