-- Pix automático (Mercado Pago): uma cobrança por parte Pix de uma venda em
-- andamento (token do formulário + número estável da parte). Roda igual no
-- PostgreSQL e no H2.
CREATE TABLE cobranca_pix (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(255) NOT NULL,
    parte INTEGER NOT NULL,
    valor NUMERIC(38,2) NOT NULL,
    -- Quantas orders já foram criadas para esta parte (muda a chave de idempotência).
    tentativa INTEGER NOT NULL,
    order_id VARCHAR(64) NOT NULL,
    qr_code VARCHAR(1000),
    qr_code_base64 VARCHAR(20000),
    status VARCHAR(20) NOT NULL,
    -- Valor que o Mercado Pago informou como pago (pode divergir do valor; aí não vira PAGA).
    valor_pago NUMERIC(38,2),
    criada_em TIMESTAMP(6) NOT NULL,
    paga_em TIMESTAMP(6),
    CONSTRAINT uk_cobranca_pix_token_parte UNIQUE (token, parte),
    CONSTRAINT uk_cobranca_pix_order UNIQUE (order_id),
    CONSTRAINT ck_cobranca_pix_status CHECK (status IN ('PENDENTE','PAGA','EXPIRADA','CANCELADA')),
    CONSTRAINT ck_cobranca_pix_valor CHECK (valor > 0),
    CONSTRAINT ck_cobranca_pix_parte CHECK (parte >= 0),
    CONSTRAINT ck_cobranca_pix_paga CHECK (status <> 'PAGA' OR (paga_em IS NOT NULL AND valor_pago = valor))
);
CREATE INDEX idx_cobranca_pix_status ON cobranca_pix(status, criada_em);

-- De onde veio cada parte Pix da venda: o Mercado Pago (com o id da order) ou o
-- Pix manual, conferido no app. Partes Pix antigas foram todas manuais.
ALTER TABLE pagamento_venda ADD COLUMN origem VARCHAR(20);
ALTER TABLE pagamento_venda ADD COLUMN mp_order_id VARCHAR(64);
UPDATE pagamento_venda SET origem = 'MANUAL' WHERE forma = 'PIX';
ALTER TABLE pagamento_venda ADD CONSTRAINT ck_pagamento_venda_origem CHECK (
    origem IS NULL OR (forma = 'PIX' AND origem IN ('MERCADO_PAGO','MANUAL')));
ALTER TABLE pagamento_venda ADD CONSTRAINT ck_pagamento_venda_mp_order CHECK (
    (origem = 'MERCADO_PAGO' AND mp_order_id IS NOT NULL)
    OR (COALESCE(origem, '') <> 'MERCADO_PAGO' AND mp_order_id IS NULL));
-- Uma order paga uma parte só.
CREATE UNIQUE INDEX uk_pagamento_venda_mp_order ON pagamento_venda(mp_order_id);
