-- Livro de movimentos do estoque: tudo que altera produto.quantidade grava um
-- movimento na mesma transação. quantidade tem sinal (entradas positivas,
-- saídas negativas), então a soma por produto é o estoque.
CREATE TABLE movimento_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    quantidade INTEGER NOT NULL,
    custo_unitario NUMERIC(38,4),
    venda_id BIGINT,
    compra_id BIGINT,
    data_hora TIMESTAMP(6) NOT NULL,
    observacao VARCHAR(255),
    CONSTRAINT fk_movimento_estoque_produto FOREIGN KEY (produto_id) REFERENCES produto(id),
    CONSTRAINT fk_movimento_estoque_venda FOREIGN KEY (venda_id) REFERENCES venda(id),
    CONSTRAINT fk_movimento_estoque_compra FOREIGN KEY (compra_id) REFERENCES compra_estoque(id),
    CONSTRAINT ck_movimento_estoque_tipo CHECK (tipo IN
        ('ENTRADA_COMPRA','ENTRADA_AJUSTE','SAIDA_VENDA','SAIDA_AJUSTE','DEVOLUCAO_CANCELAMENTO')),
    -- Entradas e devoluções somam; saídas subtraem.
    CONSTRAINT ck_movimento_estoque_sinal CHECK (
        (tipo IN ('ENTRADA_COMPRA','ENTRADA_AJUSTE','DEVOLUCAO_CANCELAMENTO') AND quantidade > 0)
        OR (tipo IN ('SAIDA_VENDA','SAIDA_AJUSTE') AND quantidade < 0)),
    -- Venda e devolução apontam para a venda; compra aponta para a compra.
    CONSTRAINT ck_movimento_estoque_venda CHECK (
        (tipo IN ('SAIDA_VENDA','DEVOLUCAO_CANCELAMENTO') AND venda_id IS NOT NULL)
        OR (tipo NOT IN ('SAIDA_VENDA','DEVOLUCAO_CANCELAMENTO') AND venda_id IS NULL)),
    CONSTRAINT ck_movimento_estoque_compra CHECK (
        (tipo = 'ENTRADA_COMPRA' AND compra_id IS NOT NULL) OR (tipo <> 'ENTRADA_COMPRA' AND compra_id IS NULL)),
    CONSTRAINT ck_movimento_estoque_custo CHECK (custo_unitario IS NULL OR custo_unitario >= 0)
);
CREATE INDEX idx_movimento_estoque_produto ON movimento_estoque(produto_id, data_hora);
CREATE INDEX idx_movimento_estoque_venda ON movimento_estoque(venda_id);

-- Saldo inicial: um movimento por produto com o estoque de hoje, para a soma bater
-- daqui em diante. Produto com estoque zero não precisa de movimento (soma zero).
INSERT INTO movimento_estoque (produto_id, tipo, quantidade, custo_unitario, data_hora, observacao)
SELECT id, 'ENTRADA_AJUSTE', quantidade, custo_unitario, CURRENT_TIMESTAMP, 'saldo inicial'
FROM produto
WHERE quantidade > 0
ORDER BY id;
