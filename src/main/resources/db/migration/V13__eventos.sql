-- Eventos (feiras, encontros): um intervalo de data e hora. A venda não guarda
-- vínculo: pertence ao evento cujo intervalo contém a sua data e hora, então
-- corrigir a data da venda já a move de evento. O intervalo é [inicio, fim):
-- o início entra, o fim não; eventos encostados (um acaba quando o outro
-- começa) não se sobrepõem. A sobreposição é recusada pela aplicação.
CREATE TABLE evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    inicio TIMESTAMP(6) NOT NULL,
    fim TIMESTAMP(6) NOT NULL,
    observacao VARCHAR(255),
    CONSTRAINT ck_evento_intervalo CHECK (fim > inicio)
);
CREATE INDEX ix_evento_inicio ON evento(inicio);
